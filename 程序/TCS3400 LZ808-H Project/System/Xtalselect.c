#include "Xtalselect.h"

/*==============================================================================
 内部定义
 *============================================================================*/

#define XTAL_STABLE_TIMEOUT  60000u // 本项目切换22.1184MHz外部晶振时限制硬件稳定等待循环次数

/*==============================================================================
 对外函数
 *============================================================================*/

/**
 * @brief  启动并选择外部晶振
 * @param  无
 * @retval 1：切换成功；0：外部晶振稳定超时
 */
bit XtalSelect_Init(void)
{
    // 本项目中该函数只在22.1184MHz外部晶振稳定后切换系统时钟，保护串口和传感器时序
    uint16 timeout;

    P_SW2 |= 0x80u;       // 开放扩展SFR写权限，允许配置本项目外部晶振寄存器
    XOSCCR = 0xC0u;       // 启动22.1184MHz外部晶振，供两个115200bps串口和1ms时基使用
    timeout = XTAL_STABLE_TIMEOUT;

    // 外部晶振故障时用有限计数退出等待，避免主板永久卡在系统初始化
    while (((XOSCCR & 0x01u) == 0u) && (timeout > 0u))
    {
        timeout--;
    }

    // 晶振未稳定时保持原系统时钟，不启动依赖22.1184MHz时序的传感器和通信任务
    if (timeout == 0u)
    {
        P_SW2 &= 0x7Fu;
        return 0;
    }

    CLKDIV = 0x00u;       // 系统时钟保持22.1184MHz不分频，匹配本项目定时参数
    CLKSEL = 0x01u;       // 将STC8H系统时钟切换到本项目外部晶振
    P_SW2 &= 0x7Fu;       // 晶振配置结束后关闭扩展SFR写权限，防止后续误写
    return 1;
}
