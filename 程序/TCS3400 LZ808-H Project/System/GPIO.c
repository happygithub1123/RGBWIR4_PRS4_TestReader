/**
 * @brief  初始化板级GPIO模式和软件I2C上拉
 * @param  无
 * @retval 无
 */
void GPIO_Init(void)
{
    // 本项目中该函数一次性配置RS485、UART、Y输出、运行灯和四路TCS3400引脚模式
    P0 &= 0x7Fu;             // 配置输出模式前先拉低P0.7，使压力RS485保持接收
    P3 &= 0xE3u;             // 配置输出模式前先关闭Y1至Y3，避免压力治具误触发
    P5 &= 0xFEu;             // 配置输出模式前先关闭Y4，避免压力治具误触发
    P0M0 = 0x80u; P0M1 = 0x00u; // P0.7用推挽控制RS485方向，其余P0脚供软件I2C
    P1M0 = 0x02u; P1M1 = 0x00u; // P1.1设为推挽输出，用作压力UART2的TXD2
    P2M0 = 0x00u; P2M1 = 0x00u;
    P3M0 = 0x1Eu; P3M1 = 0x00u; // UART1 TXD1和压力Y1至Y3控制脚使用推挽输出
    P4M0 = 0x00u; P4M1 = 0x00u;
    P5M0 = 0x11u; P5M1 = 0x00u; // 压力Y4控制脚和P5.4运行灯使用推挽输出

    P_SW2 |= 0x80u;  // 开放扩展SFR写权限，允许配置四路软件I2C内部上拉
    P0PU |= 0x16u;   // 为第1至第3路TCS3400使用的P0.1、P0.2、P0.4启用上拉
    P2PU |= 0x60u;   // 为第4路TCS3400的P2.5和P2.6启用内部上拉
    P4PU |= 0x60u;   // 为第3路TCS3400的P4.5和P4.6启用内部上拉
    P5PU |= 0x04u;   // 为第1路TCS3400的P5.2 SDA启用内部上拉
    P_SW2 &= 0x7Fu;  // GPIO上拉配置结束后关闭扩展SFR写权限
}
