/**
 * @brief  毫秒级阻塞延时
 * @param  delay_ms 延时时间，单位ms
 * @retval 无
 */
void Delay_ms(uint16 delay_ms)
{
    // 本项目中该函数只在系统初始化阶段阻塞等待晶振、GPIO和外设上电稳定
    uint16 i;

    // 按22.1184MHz和当前编译优化标定，只用于主板上电时等待硬件稳定
    while (delay_ms--)
    {
        for (i = 0u; i < 2760u; i++)
        {
            ;
        }
    }
}
